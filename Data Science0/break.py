# break statment
for i in range(0, 21):
    if i == 19:
        break
    print(i)

print("----------------------------------------------------------------------------------------------------")

# continue_statement
for v in range(0, 78):
    if v == 18:
        continue
    print(v)
    
print("----------------------------------------------------------------------------------------------------")

# pass statement
k = 3
for k in range(0, 10):
    if k == 5:
        pass # do nothing
    print(k)

print("----------------------------------------------------------------------------------------------------")